import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

ROOT = Path(__file__).resolve().parents[2]
DATA_PATH = ROOT / "data" / "processed" / "methane_pr_eos.csv"
REPORT_DIR = ROOT / "reports"

FEATURES = ["temperature_K", "pressure_Pa"]
TARGET = "Z_vapor_root"

TRAIN_T_MIN = 250.0
TRAIN_T_MAX = 370.0

def main()-> None:
    df = pd.read_csv(DATA_PATH)

    train_df = df[
        (df["temperature_K"] >= TRAIN_T_MIN)
        &(df["temperature_K"] <= TRAIN_T_MAX)
    ].copy()
    test_groups = {
        "low_temperature_extrapolation" : df[
            df["temperature_K"] < TRAIN_T_MIN
            ].copy(),
        "high_temperature_extrapolation" : df[
            df["temperature_K"] > TRAIN_T_MAX
            ].copy(),
    }

    model = RandomForestRegressor(
        n_estimators=300,
        min_samples_leaf=2,
        random_state=42,
        n_jobs=1,
    )

    model.fit(train_df[FEATURES], train_df[TARGET])

    results = {
        "train_temperature_range_K" : [TRAIN_T_MIN, TRAIN_T_MAX],
        "train_rows" : int(len(train_df)),
        "test_results" : {},
        "interpretation" : (
            "Tests evaluate temperature extrapolation outside the "
            "training range. Pressure remains within the dataset range. "
            "Targets are generated by the project PR-EOS, not experiments."
        ),
    }

    print(f"training rows: {len(train_df)}")
    print(
        "Training temperature range: "
        f"{train_df['temperature_K'].min()}-"
        f"{train_df['temperature_K'].max()} K"
    )

    for group_name, test_df in test_groups.items():
        predictions = model.predict(test_df[FEATURES])
        actual = test_df[TARGET].to_numpy()

        metrics = {
            "test_rows" : int(len(test_df)),
            "temperature_min_K" : float(test_df['temperature_K'].min()),
            "temperature_max_K" : float(test_df['temperature_K'].max()),
            "mae" : float(mean_absolute_error(actual, predictions)),
            "rmse" : float(np.sqrt(mean_squared_error(actual, predictions))),
            "r2" : float(r2_score(actual, predictions)),
        }

        results["test_results"][group_name] = metrics

        print(f"\n{group_name}")
        print(json.dumps(metrics, indent=2))

    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    output_path = REPORT_DIR / "extrapolation_metrics.json"
    output_path.write_text(
        json.dumps(results, indent=2),
        encoding="utf-8",
    )

    print(f"\nResullts saved to: {output_path}")

if __name__ == "__main__":
    main()
